/**
 * Generates utils/generated/hsmsDiacriticMap.ts from legacy HSMS RegexReplaces.
 *
 * Note: assets/dic/hsms.src is the DB_MAP lemmatization dictionary, not character
 * mappings. Diacritic rules mirror HSMSTools/HSMSParser/settings.ini [RegexReplaces].
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const SETTINGS_INI = path.join(root, "..", "HSMSTools", "HSMSParser", "settings.ini");
const OUTPUT = path.join(root, "utils", "generated", "hsmsDiacriticMap.ts");

const PRIME_CHARS = ["'", "\u2018", "\u2019", "\u0060"];

function decodeHtmlEntity(value) {
  const trimmed = value.trim();
  const named = { amp: "&", para: "¶" };
  if (named[trimmed]) return named[trimmed];

  const m = trimmed.match(/^&#(\d+);?$/);
  if (m) return String.fromCodePoint(Number(m[1]));

  return trimmed;
}

function parseRegexReplaces(iniText) {
  const section = iniText.match(/\[RegexReplaces\]([\s\S]*?)(?:\n\[|$)/)?.[1] ?? "";
  const pairs = [];
  for (const line of section.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith(";")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    pairs.push({
      pattern: trimmed.slice(0, eq).trim(),
      replacement: decodeHtmlEntity(trimmed.slice(eq + 1)),
    });
  }
  return pairs;
}

function expandPatternToKeys(pattern) {
  if (pattern === "&[‘'’]?" || pattern.startsWith("&")) return [];
  if (pattern === "%") return [];

  const keys = new Set();

  if (/^[Cc]\[/.test(pattern) && pattern.endsWith("]")) {
    const letter = pattern[0];
    for (const p of PRIME_CHARS) keys.add(`${letter}${p}`);
    keys.add(`${letter}'`);
    return [...keys];
  }

  const accentMatch = pattern.match(/^([aeijouynAEIJOUYN])@\?(.+)$/);
  if (accentMatch) {
    const [, letter, markPart] = accentMatch;
    const marks = [];
    if (markPart === "`") marks.push("`");
    else if (markPart === "\\^" || markPart === "^") marks.push("^");
    else if (markPart === "~") marks.push("~");
    else if (markPart === "[‘'’]") {
      for (const p of PRIME_CHARS) marks.push(p);
    }

    for (const mark of marks) {
      keys.add(`${letter}${mark}`);
      keys.add(`${letter}@${mark}`);
      const upper = letter.toUpperCase();
      keys.add(`${upper}${mark}`);
      keys.add(`${upper}@${mark}`);
    }
    return [...keys];
  }

  return [];
}

function buildMap(pairs) {
  const map = {};
  for (const { pattern, replacement } of pairs) {
    if (!replacement || replacement.startsWith("&")) continue;
    for (const key of expandPatternToKeys(pattern)) {
      map[key] = replacement;
    }
  }
  return map;
}

function main() {
  if (!fs.existsSync(SETTINGS_INI)) {
    console.error(`Missing legacy settings: ${SETTINGS_INI}`);
    process.exit(1);
  }

  const iniText = fs.readFileSync(SETTINGS_INI, "utf8");
  const pairs = parseRegexReplaces(iniText);
  const map = buildMap(pairs);

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });

  const ts = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-diacritic-map.mjs — do not edit manually.
// Source: HSMSTools/HSMSParser/settings.ini [RegexReplaces] (legacy CharRegexReplacements).

export const HSMS_DIACRITIC_MAP: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;

  fs.writeFileSync(OUTPUT, ts, "utf8");
  console.log(`Wrote ${Object.keys(map).length} diacritic keys → ${OUTPUT}`);
}

main();
