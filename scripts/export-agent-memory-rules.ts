/**
 * Export Proofer / linter / paleography rules as machine-readable assets
 * for Azure Foundry agent memory / file_search upload.
 *
 *   npm run export:agent-memory
 *
 * Writes:
 *   assets/agent-memory/hsms-agent-rules.json
 *   assets/agent-memory/hsms-agent-rules.txt
 *   assets/agent-memory/hsms-linter-rules.json
 *   assets/agent-memory/hsms-proofer-rules.json
 *   assets/agent-memory/README.md
 */
import fs from "node:fs";
import path from "node:path";
import {
  buildAgentMemoryPayload,
  formatAgentMemoryText,
  LINTER_AGENT_RULES,
  PALEOGRAPHIC_AGENT_RULES,
  PROOFER_AGENT_RULES,
  type AgentMemoryExportPayload,
  type HsmsAgentRule,
} from "../utils/hsmsAgentRuleCatalog";

const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "assets", "agent-memory");

function writeJson(filePath: string, data: unknown): void {
  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, "utf8");
}

function subsetPayload(
  base: AgentMemoryExportPayload,
  rules: readonly HsmsAgentRule[],
  description: string,
): AgentMemoryExportPayload {
  return {
    ...base,
    description,
    ruleCount: rules.length,
    rules: [...rules],
  };
}

function writeReadme(): void {
  const body = `# HSMS Agent Memory Assets

Generated by \`npm run export:agent-memory\` from \`utils/hsmsAgentRuleCatalog.ts\`
(derived from \`utils/hsmsLinter.ts\` + \`utils/prooferIncidents.ts\`).

## Files

| File | Use |
|------|-----|
| \`hsms-agent-rules.txt\` | Paste / upload into Foundry agent memory or \`file_search\` |
| \`hsms-agent-rules.json\` | Full machine-readable catalog (all sources) |
| \`hsms-linter-rules.json\` | Linter-only codes |
| \`hsms-proofer-rules.json\` | Proofer incident codes |

## Upload checklist

1. Run \`npm run export:agent-memory\` after changing linter/proofer guidance.
2. In Azure AI Foundry → Agent → Knowledge / Memory (or \`file_search\` store), upload \`hsms-agent-rules.txt\` (and optionally the JSON).
3. Keep system instructions aligned with \`docs/prompt-hsms-transcriber.md\`.
4. Do **not** expect the LLM to replace \`lintHsmsTranscription\` — client remains the gatekeeper.

## Boundary reminder

- **Agent:** paleographic decipherment + draft HSMS ASCII following these rules.
- **Client:** lexer, spatial AST, deterministic lint / Proofer audit, parchment render.
`;
  fs.writeFileSync(path.join(OUT_DIR, "README.md"), body, "utf8");
}

function main(): void {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const payload = buildAgentMemoryPayload();

  writeJson(path.join(OUT_DIR, "hsms-agent-rules.json"), payload);
  fs.writeFileSync(
    path.join(OUT_DIR, "hsms-agent-rules.txt"),
    formatAgentMemoryText(payload),
    "utf8",
  );

  writeJson(
    path.join(OUT_DIR, "hsms-linter-rules.json"),
    subsetPayload(
      payload,
      [...PALEOGRAPHIC_AGENT_RULES, ...LINTER_AGENT_RULES],
      "Paleography + hsmsLinter structural codes for agent memory.",
    ),
  );
  writeJson(
    path.join(OUT_DIR, "hsms-proofer-rules.json"),
    subsetPayload(
      payload,
      PROOFER_AGENT_RULES,
      "Proofer incident codes (señala; el editor decide) for agent memory.",
    ),
  );
  writeReadme();

  console.log(
    `Wrote ${payload.ruleCount} rules → ${path.relative(ROOT, OUT_DIR)} ` +
      `(txt + json catalogs)`,
  );
}

main();
