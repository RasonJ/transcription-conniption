import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(__dirname, "..");
const enPath = join(root, "i18n", "locales", "en.json");
const outDir = join(root, "i18n", "generated");
const outPath = join(outDir, "messageKeys.ts");

export function isDescriptionKey(key: string): boolean {
  return key.startsWith("_") && key.endsWith(".description");
}

export function collectMessageKeys(catalog: Record<string, unknown>): string[] {
  return Object.keys(catalog)
    .filter((key) => !isDescriptionKey(key))
    .sort();
}

export function renderMessageKeysModule(keys: string[]): string {
  const union = keys.map((key) => `  | ${JSON.stringify(key)}`).join("\n");
  return [
    "// Generated by scripts/i18n-types.ts from i18n/locales/en.json. Do not edit.",
    `export type MessageKey =\n${union};`,
    "",
  ].join("\n");
}

if (require.main === module) {
  const en = JSON.parse(readFileSync(enPath, "utf8")) as Record<string, unknown>;
  const keys = collectMessageKeys(en);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(outPath, renderMessageKeysModule(keys));
  console.log(`Wrote ${keys.length} keys to i18n/generated/messageKeys.ts`);
}
