function recipe(
  r: Omit<R, "version" | "requires" | "slots" | "precompute"> &
    Partial<Pick<R, "version" | "requires" | "slots" | "precompute">>,
): R {
  return {
    version: 1,
    requires: r.tier === "D" ? ["pos_tagging"] : ["facets"],
    slots: [],
    precompute: r.slots?.length ? "on_demand" : "eager",
    ...r,
  };
}

